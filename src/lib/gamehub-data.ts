/**
 * Generic provider fallback.
 *
 * Automated competitions should resolve region-specific
 * broadcast information through the Worker/broadcast API.
 * This helper intentionally contains no fixture-specific
 * or competition-specific broadcast assumptions.
 */
export function getProviderIdsForGame(
  game: Game,
  _region: string,
): string[] {
  const providerIds =
    game.providerIds?.filter(
      Boolean,
    );

  if (
    providerIds &&
    providerIds.length > 0
  ) {
    return Array.from(
      new Set(
        providerIds,
      ),
    );
  }

  if (game.providerId) {
    return [
      game.providerId,
    ];
  }

  return ["tbd"];
}

export function timeZoneForRegion(
  region: string,
) {
  /*
   * SeasonCaddy treats the United States as
   * one broadcast region.
   *
   * Eastern Time is the canonical U.S.
   * calendar timezone. User-facing fixture
   * displays will separately show both
   * ET and PT.
   */
  if (
    region === "United States" ||
    region.startsWith(
      "United States ·",
    )
  ) {
    return "America/New_York";
  }

  if (
    region ===
    "United Kingdom"
  ) {
    return "Europe/London";
  }

  if (
    region === "Canada"
  ) {
    return "America/Toronto";
  }

  return "America/New_York";
}

export function formatRegionalTime(
  kickoff: string | null,
  region: string,
) {
  if (!kickoff) {
    return "Time TBD";
  }

  const date =
    new Date(kickoff);

  if (
    Number.isNaN(
      date.getTime(),
    )
  ) {
    return "Time TBD";
  }

  /*
   * North American television-style display.
   *
   * United States and Canada both show:
   *
   * 3:00 PM ET / 12:00 PM PT
   *
   * They remain separate broadcast regions;
   * this only controls how kickoff times
   * are displayed to the user.
   */
  if (
    region ===
      "United States" ||
    region.startsWith(
      "United States ·",
    ) ||
    region ===
      "Canada"
  ) {
    const eastern =
      new Intl.DateTimeFormat(
        "en-US",
        {
          hour:
            "numeric",

          minute:
            "2-digit",

          timeZone:
            "America/New_York",
        },
      ).format(date);

    const pacific =
      new Intl.DateTimeFormat(
        "en-US",
        {
          hour:
            "numeric",

          minute:
            "2-digit",

          timeZone:
            "America/Los_Angeles",
        },
      ).format(date);

    return `${eastern} ET / ${pacific} PT`;
  }

  /*
   * United Kingdom and any future
   * single-timezone displays continue
   * using their regional timezone.
   */
  return new Intl.DateTimeFormat(
    "en-US",
    {
      hour:
        "numeric",

      minute:
        "2-digit",

      timeZone:
        timeZoneForRegion(
          region,
        ),
    },
  ).format(date);
}

export function formatKickoff(
  iso: string | null,
  scheduledDate?: string,
  scheduleLabel?: string,
  timeZone?: string,
) {
  if (!iso) {
    if (scheduleLabel) {
      return `${scheduleLabel} · Time TBD`;
    }

    if (!scheduledDate) {
      return "Date & time TBD";
    }

    return `${new Date(
      `${scheduledDate}T12:00:00`,
    ).toLocaleDateString(
      undefined,
      {
        weekday: "short",
        month: "short",
        day: "numeric",
        timeZone,
      },
    )} · Time TBD`;
  }

  return new Date(
    iso,
  ).toLocaleString(
    undefined,
    {
      weekday: "short",
      month: "short",
      day: "numeric",
      hour: "numeric",
      minute: "2-digit",
      timeZone,
    },
  );
}

export function formatTime(
  iso: string | null,
  timeZone?: string,
) {
  if (!iso) {
    return "TBD";
  }

  return new Date(
    iso,
  ).toLocaleTimeString(
    undefined,
    {
      hour: "numeric",
      minute: "2-digit",
      timeZone,
    },
  );
}

