function fixtureTimestamp(
  value: string | null | undefined,
) {
  if (!value) {
    return null;
  }

  const timestamp = new Date(
    value,
  ).getTime();

  return Number.isNaN(
    timestamp,
  )
    ? null
    : timestamp;
}

function expectedLiveDurationMs(
  sport: string,
) {
  return (
    LIVE_DURATION_BY_SPORT_MS[
      sport.trim().toLowerCase()
    ] ??
    DEFAULT_LIVE_DURATION_MS
  );
}

export function gameLiveEndTime(
  game: Game,
) {
  const kickoff =
    fixtureTimestamp(
      game.kickoff,
    );

  if (kickoff === null) {
    return null;
  }

  const fallbackEnd =
    kickoff +
    expectedLiveDurationMs(
      game.sport,
    );

  const providerEnd =
    fixtureTimestamp(
      game.endTime,
    );

  if (
    providerEnd !== null &&
    providerEnd > kickoff
  ) {
    return providerEnd;
  }

  return fallbackEnd;
}

export function isGameLive(
  game: Game,
  now = Date.now(),
) {
  if (
    game.status ===
    "Final"
  ) {
    return false;
  }

  const kickoff =
    fixtureTimestamp(
      game.kickoff,
    );

  if (kickoff === null) {
    return (
      game.status ===
      "Live now"
    );
  }

  if (now < kickoff) {
    return false;
  }

  const liveEnd =
    gameLiveEndTime(
      game,
    );

  return (
    liveEnd !== null &&
    now < liveEnd
  );
}

export function isUpcomingOrLiveGame(
  game: Game,
  now = Date.now(),
) {
  if (
    isGameLive(
      game,
      now,
    )
  ) {
    return true;
  }

  if (
    game.status ===
    "Final"
  ) {
    return false;
  }

  const kickoff =
    fixtureTimestamp(
      game.kickoff,
    );

  if (kickoff !== null) {
    return kickoff >= now;
  }

  if (
    game.scheduledDate
  ) {
    const scheduledEnd =
      new Date(
        `${game.scheduledDate}T23:59:59`,
      ).getTime();

    return (
      !Number.isNaN(
        scheduledEnd,
      ) &&
      scheduledEnd >= now
    );
  }

  return false;
}

export function countdown(
  target: string | null,
) {
  if (!target) {
    return "Time TBD";
  }

  const diff =
    new Date(
      target,
    ).getTime() -
    Date.now();

  if (diff <= 0) {
    return "Started";
  }

  const d = Math.floor(
    diff / 86400000,
  );

  const h = Math.floor(
    (diff % 86400000) /
      3600000,
  );

  const m = Math.floor(
    (diff % 3600000) /
      60000,
  );

  const s = Math.floor(
    (diff % 60000) /
      1000,
  );

  return `${d}d ${String(
    h,
  ).padStart(
    2,
    "0",
  )}h ${String(
    m,
  ).padStart(
    2,
    "0",
  )}m ${String(
    s,
  ).padStart(
    2,
    "0",
  )}s`;
}
